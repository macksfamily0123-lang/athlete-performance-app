import assert from 'node:assert/strict';
import fs from 'node:fs';
import {routineStatus,trendGeometry,formatChartValue,percentageImprovement} from '../lib/performance-ui.mjs';
let checks=0;
function check(condition,label){assert.ok(condition,label);checks++}
check(percentageImprovement(12,11,true)===8.3,'lower-is-better improvement is a percentage');
check(percentageImprovement(10,12,false)===20,'higher-is-better improvement is a percentage');
check(percentageImprovement(0,12,false)===0,'zero baseline is safe');
const day='2026-09-30',week='2026-09-28';
check(!routineStatus([],[],day,week).dailyComplete,'empty readiness remains incomplete');
check(!routineStatus([],[],day,week).weeklyComplete,'empty review remains incomplete');
check(!routineStatus([{date:'2026-09-29'}],[{weekStart:'2026-09-21'}],day,week).dailyComplete,'yesterday is not today');
check(!routineStatus([],[{weekStart:'2026-09-21'}],day,week).weeklyComplete,'last week is not this week');
check(routineStatus([{date:day}],[],day,week).dailyComplete,'today completes the check-in');
check(routineStatus([],[{weekStart:week}],day,week).weeklyComplete,'this week completes the review');
check(trendGeometry([])===null,'no invented chart for an empty series');
check(trendGeometry([NaN,Infinity])===null,'invalid values do not create a chart');
const flat=trendGeometry([20,20,20]);
check(flat.points.every(p=>p.y===90),'flat series is centered');
check(trendGeometry([20]).points[0].x===260,'one result is centered');
const growing=trendGeometry([10,15,20]);
check(growing.points[0].y>growing.points[2].y,'higher values rise');
check(growing.points[0].x<growing.points[2].x,'oldest to newest left to right');
check(growing.points.every(p=>p.x>=36&&p.x<=484&&p.y>=36&&p.y<=144),'chart stays within bounds');
check(formatChartValue(12.345)==='12.35','chart numbers are readable');
const app=fs.readFileSync('components/AthleteApp.tsx','utf8');
const css=fs.readFileSync('app/redesign.css','utf8');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
check(pkg.version==='72.3.117','RC67 metadata');
check(app.indexOf('<PlayerRoutinePriorityBanners')<app.indexOf('{betaBridge?.sportProfiles?.length?<div className="sportSelectorBlock'),'routine actions precede sport workspace');
check(app.includes('canRole(effectiveRole,"playerDailyCheckIn")'),'routine completion respects effective role permissions');
check(app.includes('<SharedRoutineStatus role={effectiveRole}'),'Parent and Coach receive read-only status');
check(app.includes('onNavigate("Coach","shared-weekly-reviews")'),'shared review opens its exact section');
check(app.includes('ancestor instanceof HTMLDetailsElement)ancestor.open=true'),'targeted navigation opens collapsed ancestors');
check(app.includes('window.addEventListener("elite:destination",openDestination)'),'same-tab CoachHub destination changes subview');
check(app.includes('id="testing-history"'),'testing history has a direct destination');
check(app.includes('previous?improvement(previous.value,r.value,Boolean(t?.lowerBetter)):null'),'history change respects lower-is-better tests');
check(app.includes('const TRACKER_CONNECTIVITY_ENABLED=false'),'trackers remain disabled');
check(!app.includes('build signal'),'plain-language copy');
check(css.includes('prefers-reduced-motion:reduce'),'reduced-motion support');
check(css.includes('grid-template-columns:repeat(5,minmax(0,1fr))'),'five-column navigation dock');
check(css.includes('min-height:44px'),'touch target baseline');
check(css.includes('@media(max-width:380px)')&&css.includes('@media(max-width:900px)'),'phone and tablet breakpoints');
check(app.includes('if(!canRole(accountRole,"playerWeeklyReview"))return;'),'weekly writes follow the existing role permission');
check(app.includes('const usable=points;')&&!app.includes('points:[50,50]'),'empty sparklines do not fabricate points');
check(app.includes('hasPerformanceSummary?intelligenceScore:"—"'),'no default progress score for missing data');
console.log(`RC67 redesign checks passed (${checks}/${checks}).`);
